// Writes src/lib/covers.ts from public/images/covers/<category>/<name>.jpg so
// the app knows which stock covers exist without reading the disk at runtime.
// Run after adding or removing cover photos: node scripts/list-covers.mjs
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = "public/images/covers";
const files = {};
for (const category of readdirSync(ROOT)) {
  const dir = join(ROOT, category);
  if (!statSync(dir).isDirectory()) continue;
  files[category] = readdirSync(dir)
    .filter((f) => f.endsWith(".jpg"))
    .map((f) => f.slice(0, -4))
    .sort();
}
const body = Object.entries(files)
  .map(([category, names]) => `  ${category}: [${names.map((n) => JSON.stringify(n)).join(", ")}],`)
  .join("\n");
writeFileSync(
  "src/lib/covers.ts",
  `// Generated by scripts/list-covers.mjs: stock covers under public/images/covers.\n// Each category has a "default"; the rest are named after sub-activities.\nexport const COVER_FILES: Record<string, readonly string[]> = {\n${body}\n};\n`,
);
console.log("covers:", Object.values(files).reduce((n, list) => n + list.length, 0));
